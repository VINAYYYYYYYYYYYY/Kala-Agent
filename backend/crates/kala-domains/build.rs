//! Native-only build-time implementation provenance.
//!
//! The build script hashes this crate's own Rust sources and the source trees
//! of its accepted local dependencies, then embeds the resulting domain source
//! digests as `'static` constants. It does not invoke Python and does not read
//! Python source files. The digest algorithm is shared with
//! [`kala_domains::source_audit`] through `src/source_digest_core.rs`, so the
//! library can recompute and verify the embedded values against the current
//! tree without duplicating the rules.

#[path = "src/source_digest_core.rs"]
mod source_digest_core;

use std::env;
use std::fs;
use std::path::PathBuf;

use source_digest_core::{DependencySourceRoot, SourceRoots};

fn main() {
    println!("cargo:rerun-if-changed=src");
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=Cargo.toml");

    let manifest_dir = PathBuf::from(
        env::var("CARGO_MANIFEST_DIR").expect("cargo always sets CARGO_MANIFEST_DIR"),
    );
    let crates_dir = manifest_dir
        .parent()
        .expect("kala-domains lives under the crates directory")
        .to_path_buf();
    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("cargo always sets OUT_DIR"));

    let dependencies = ["kala-budget", "kala-json", "kala-contracts"]
        .into_iter()
        .map(|name| {
            let root = crates_dir.join(name);
            println!("cargo:rerun-if-changed={}", root.join("src").display());
            println!(
                "cargo:rerun-if-changed={}",
                root.join("Cargo.toml").display()
            );
            if root.join("build.rs").is_file() {
                println!("cargo:rerun-if-changed={}", root.join("build.rs").display());
            }
            DependencySourceRoot::new(name, root)
        })
        .collect::<Vec<_>>();
    let roots = SourceRoots::new(manifest_dir.join("src"), dependencies);

    let mut generated = String::new();
    generated.push_str(
        "// Generated by build.rs from this crate's Rust sources and accepted\n\
         // local dependency source trees. Do not edit.\n",
    );
    for (domain, prefix) in [
        ("mechanical", "MECHANICAL"),
        ("building", "BUILDING"),
        ("wing", "WING"),
    ] {
        let digests = source_digest_core::domain_source_digests(&roots, domain)
            .unwrap_or_else(|error| panic!("cannot digest the {domain} Rust sources: {error}"));
        generated.push_str(&format!(
            "pub const {prefix}_MODULE_DIGEST: &str = \"{}\";\n",
            digests.module_digest
        ));
        generated.push_str(&format!(
            "pub const {prefix}_PACKAGE_DIGEST: &str = \"{}\";\n",
            digests.package_digest
        ));
    }

    fs::write(out_dir.join("native_source_digests.rs"), generated)
        .expect("write generated native source digests");
}
