#!/usr/bin/env python3
"""Generate the Unicode class tables used by the Rust pattern engine.

The tool protocol matches schema patterns with CPython's `re` semantics, and
CPython's `\\w`, `\\d` and `\\s` are defined by `str.isalnum`, `str.isdecimal`
and `str.isspace` rather than by the Unicode `Alphabetic`/`White_Space`
properties. This script extracts the exact code point ranges from the live
interpreter so the Rust engine reproduces CPython byte for byte.

The generated file is committed to the crate; the crate never runs Python.

Usage: python generate_unicode_tables.py <output.rs>
"""

from __future__ import annotations

import sys
from pathlib import Path


def ranges(predicate) -> list[tuple[int, int]]:
    out: list[tuple[int, int]] = []
    start: int | None = None
    for code_point in range(0x110000):
        if predicate(code_point):
            if start is None:
                start = code_point
        elif start is not None:
            out.append((start, code_point - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def render(name: str, values: list[tuple[int, int]]) -> str:
    lines = [
        f"/// Code point ranges for the CPython `{name}` predicate.",
        f"pub(crate) const {name}: &[(u32, u32)] = &[",
    ]
    for low, high in values:
        lines.append(f"    (0x{low:04X}, 0x{high:04X}),")
    lines.append("];")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    if len(sys.argv) != 2:
        print("usage: generate_unicode_tables.py <output.rs>", file=sys.stderr)
        return 2
    output = Path(sys.argv[1])

    alnum = ranges(lambda cp: chr(cp).isalnum())
    decimal = ranges(lambda cp: chr(cp).isdecimal())
    space = ranges(lambda cp: chr(cp).isspace())

    header = """//! Unicode class tables matching CPython's `str` predicates.
//!
//! Generated by `tools/generate_unicode_tables.py` from the live CPython
//! interpreter. Do not edit by hand.
//!
//! CPython defines the regular expression classes `\\w`, `\\d` and `\\s` in
//! terms of `str.isalnum`, `str.isdecimal` and `str.isspace`, which are not
//! the same sets as the Unicode `Alphabetic` and `White_Space` properties
//! used by most other regular expression engines. These tables reproduce the
//! CPython sets exactly so a schema pattern behaves identically.

"""
    body = "\n".join(
        [
            render("ALNUM_RANGES", alnum),
            render("DECIMAL_RANGES", decimal),
            render("SPACE_RANGES", space),
        ]
    )
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(header + body, encoding="utf-8")
    print(
        f"wrote {output} with {len(alnum)} alnum, {len(decimal)} decimal "
        f"and {len(space)} space ranges"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
